/**
 * Generates the frontend artifacts from the OpenAPI document (single source of truth):
 *   docs/postman/Zellavora-Nexus.postman_collection.json
 *   docs/FRONTEND_API_GUIDE.md
 *   docs/API_ENDPOINT_INDEX.csv
 *   docs/API_RENAME_MAP.md
 *
 *   npm run docs:artifacts          write
 *   npm run docs:artifacts -- --check   fail when committed files are stale
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { promisify } from 'node:util';
import '../src/modules/index.js';
import { buildOpenApi } from '../src/platform/openapi/buildSpec.js';
import { routeRegistry } from '../src/platform/http/route.js';
import { ERROR_CODES } from '../src/platform/openapi/shared.js';
import { stringify as csvStringify } from 'csv-stringify/sync';

// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Json = Record<string, any>;
const check = process.argv.includes('--check');
const version = process.env.APP_VERSION ?? '1.0.0';
const doc = buildOpenApi({ version, audience: 'frontend' }) as Json;
const METHODS = ['get', 'post', 'patch', 'put', 'delete'];

interface Row {
  tag: string; operationId: string; method: string; path: string; summary: string; permission: string;
  request: string; success: string; errors: string; flag: string; idempotency: string;
}
const refName = (s: Json | undefined): string => {
  if (!s) return '';
  if (typeof s.$ref === 'string') return s.$ref.split('/').pop()!;
  if (s.type === 'string' && s.format === 'binary') return 'binary';
  return s.type ? String(s.type) : '';
};

const rows: Row[] = [];
for (const [path, item] of Object.entries(doc.paths as Json)) {
  for (const method of METHODS) {
    const op = item[method] as Json | undefined;
    if (!op) continue;
    const ok = Object.entries(op.responses as Json).find(([s]) => /^2/.test(s));
    const okMedia = ok?.[1].content ? (Object.values(ok[1].content)[0] as Json) : undefined;
    const reqMedia = op.requestBody ? (Object.values(op.requestBody.content)[0] as Json) : undefined;
    rows.push({
      tag: op.tags[0], operationId: op.operationId, method: method.toUpperCase(), path, summary: op.summary,
      permission: op['x-required-permission'] ?? (op.security?.length ? 'any signed-in user' : 'public'),
      request: refName(reqMedia?.schema), success: ok ? `${ok[0]}${okMedia ? ` ${refName(okMedia.schema)}` : ''}` : '',
      errors: Object.keys(op.responses).filter((s) => !/^2/.test(s)).join(' '),
      flag: op['x-feature-flag'] ?? '', idempotency: op['x-idempotent'] ? String(op['x-idempotent']) : '',
    });
  }
}

// ---- CSV -------------------------------------------------------------------------------------------------------
const csv = csvStringify(rows.map((r) => [r.tag, r.operationId, r.method, r.path, r.summary, r.permission, r.request, r.success, r.errors, r.flag, r.idempotency]), {
  header: true, columns: ['module', 'operationId', 'method', 'path', 'summary', 'permission', 'requestBody', 'successResponse', 'errorStatuses', 'featureFlag', 'idempotency'],
});

// ---- guide -----------------------------------------------------------------------------------------------------
const esc = (s: string) => s.replace(/\|/g, '\\|');
const byTag = new Map<string, Row[]>();
for (const r of rows) (byTag.get(r.tag) ?? byTag.set(r.tag, []).get(r.tag)!).push(r);
const tagOrder = (doc.tags as Json[]).map((t) => t.name as string);
const permsToOps = new Map<string, string[]>();
for (const r of rows) if (r.permission.includes(':')) (permsToOps.get(r.permission) ?? permsToOps.set(r.permission, []).get(r.permission)!).push(r.operationId);

const enums = Object.entries(doc.components.schemas as Json).filter(([, s]) => Array.isArray(s.enum));
const guide = [
  '# Frontend API guide',
  '',
  '_Generated by `npm run docs:artifacts` from the live OpenAPI document. Do not edit by hand; change the route definitions or `src/modules/*/docs.ts`._',
  '',
  `API version **${version}** · ${rows.length} operations · base path \`/api/v1\` · interactive docs at \`/api/docs\` and \`/api/redoc\` (non-production).`,
  '',
  '## How to use this guide',
  '1. Read **Getting started** (the description at the top of Swagger UI / `docs/openapi.yaml`) once: login, tenancy, pagination, idempotency, errors.',
  '2. Find your module below. Every operation name (`operationId`) is also the method name in the typed client (`sdk/`), e.g. `api.createProject(...)`.',
  '3. For each screen call `getMyPermissions` once and hide actions the user lacks.',
  '',
  '## Auth flow',
  '```',
  'POST /auth/login            -> accessToken (15 min) + refreshToken        [loginWithPassword]',
  '  401 mfa_required          -> repeat login with mfaCode',
  'GET  /auth/me               -> user, organizations, permissions           [getCurrentUser]',
  'POST /auth/refresh          -> new accessToken AND new refreshToken       [refreshAccessToken]',
  'POST /auth/switch-organization -> token for another organization         [switchOrganization]',
  'POST /auth/logout           -> revoke this session                        [logoutCurrentSession]',
  '```',
  '',
  '## Pagination walk-through',
  '```',
  'GET /projects?limit=2            -> { data: [p1, p2], meta: { limit: 2, nextCursor: "eyJ2…" } }',
  'GET /projects?limit=2&cursor=eyJ2… -> { data: [p3], meta: { limit: 2, nextCursor: null } }   // last page',
  '```',
  '',
  '## Idempotency walk-through',
  '```',
  'POST /invoices/{invoiceId}/send   Idempotency-Key: 7b1c…   -> 200 { number: "INV-2026-0001" }',
  'POST /invoices/{invoiceId}/send   Idempotency-Key: 7b1c…   -> 200 same body, header Idempotent-Replay: true',
  'POST /invoices/{otherId}/send     Idempotency-Key: 7b1c…   -> 422 IDEMPOTENCY_KEY_REUSED',
  '```',
  '',
  '## Error codes',
  '| Code | HTTP | Meaning | Frontend handling |', '|---|---|---|---|',
  ...ERROR_CODES.map((e) => `| \`${e.code}\` | ${e.status} | ${esc(e.meaning)} | ${esc(e.frontend)} |`),
  '',
  '## Operations by module',
  ...tagOrder.flatMap((tag) => {
    const list = byTag.get(tag);
    if (!list) return [];
    const t = (doc.tags as Json[]).find((x) => x.name === tag)!;
    return [
      '', `### ${tag}`, '', String(t.description).split('\n')[0]!, '',
      '| operationId | method | path | summary | permission | request body | success response | notable errors |', '|---|---|---|---|---|---|---|---|',
      ...list.map((r) => `| \`${r.operationId}\` | ${r.method} | \`${r.path.replace('/api/v1', '')}\` | ${esc(r.summary)} | ${r.permission.includes(':') ? `\`${r.permission}\`` : r.permission} | ${r.request ? `\`${r.request}\`` : ''} | ${r.success ? `\`${r.success}\`` : ''} | ${r.errors.replace(/\b(500|503|429)\b ?/g, '').trim()} |`),
    ];
  }),
  '',
  '## Enum catalog',
  ...(enums.length ? enums.flatMap(([name, s]) => ['', `**${name}**: ${(s.enum as string[]).map((v) => `\`${v}\``).join(', ')}`]) : ['_Status values are documented per property in the operation schemas._']),
  '',
  '## Permission catalog',
  'Permission keys use `resource:action`. The list below shows which operations each key unlocks.',
  '',
  '| Permission | Operations |', '|---|---|',
  ...[...permsToOps].sort(([a], [b]) => a.localeCompare(b)).map(([p, ops]) => `| \`${p}\` | ${ops.map((o) => `\`${o}\``).join(', ')} |`),
  '',
].join('\n');

// ---- rename map ------------------------------------------------------------------------------------------------
const renamed = routeRegistry.map((r) => ({
  oldKey: r.catalogKey!, newKey: `${r.method.toUpperCase()} ${r.path}`, operationId: r.operationId!, summary: r.summary,
}));
const renameMap = [
  '# API rename map',
  '',
  '_Generated by `npm run docs:artifacts`. Every route now has a unique camelCase `operationId` (the method name in the typed client); path parameters named `:id` were renamed after their resource. All paths keep the `/api/v1` prefix; request and response bodies are unchanged._',
  '',
  `Routes: ${renamed.length} · path parameter renames: ${renamed.filter((r) => r.oldKey !== r.newKey).length} · route moves: 1 (\`GET /help/articles/:slug\` → \`GET /help/articles/by-slug/{slug}\`, because \`PATCH /help/articles/{articleId}\` shared the same URL shape).`,
  '',
  '| Old (method path) | New (method path) | operationId |', '|---|---|---|',
  ...renamed.map((r) => `| \`${r.oldKey}\` | \`${r.newKey.replace(/:(\w+)/g, '{$1}')}\` | \`${r.operationId}\` |`),
  '',
].join('\n');

// ---- postman ---------------------------------------------------------------------------------------------------
async function postman(): Promise<string> {
  const { default: Converter } = (await import('openapi-to-postmanv2')) as unknown as { default: { convert: (i: object, o: object, cb: (e: Error | null, r: Json) => void) => void } };
  const result = await promisify(Converter.convert.bind(Converter))({ type: 'json', data: structuredClone(doc) }, { folderStrategy: 'Tags', requestParametersResolution: 'Example', exampleParametersResolution: 'Example', includeAuthInfoInExample: false, parametersResolution: 'Example' });
  if (!result.result) throw new Error(`postman conversion failed: ${result.reason}`);
  const col = result.output[0].data as Json;
  col.info.name = 'Zellavora Nexus API';
  col.info.description = 'Generated from docs/openapi.yaml. Run **loginWithPassword** first: its test script stores `accessToken` and `refreshToken` as collection variables.';
  col.variable = [
    { key: 'baseUrl', value: 'http://localhost:3000', type: 'string' },
    { key: 'accessToken', value: '', type: 'string' },
    { key: 'refreshToken', value: '', type: 'string' },
  ];
  col.auth = { type: 'bearer', bearer: [{ key: 'token', value: '{{accessToken}}', type: 'string' }] };
  delete col.info._postman_id; // random per run: strip for deterministic output
  const walk = (items: Json[]) => {
    for (const it of items) {
      delete it.id;
      if (it.item) { walk(it.item); continue; }
      if (it.request?.auth?.type === 'bearer') delete it.request.auth; // inherit the collection bearer ({{accessToken}}); public operations keep noauth
      it.response = []; // example responses are in the OpenAPI document; keeps the collection small
      const url = it.request?.url;
      if (url) {
        const raw = String(url.raw ?? '').replace(/^https?:\/\/[^/]+/, '{{baseUrl}}').replace(/^\{\{baseUrl\}\}/, '{{baseUrl}}');
        url.raw = raw.startsWith('{{baseUrl}}') ? raw : `{{baseUrl}}${raw}`;
        url.host = ['{{baseUrl}}'];
        delete url.protocol; delete url.port;
      }
      const path = Array.isArray(it.request?.url?.path) ? it.request.url.path.join('/') : '';
      if (it.request?.method === 'POST' && (path === 'api/v1/auth/login' || path === 'api/v1/auth/switch-organization' || path === 'api/v1/auth/refresh') && /login|switch|refresh/i.test(path)) {
        it.event = [{ listen: 'test', script: { type: 'text/javascript', exec: [
          'const res = pm.response.json();',
          'if (res.data && res.data.accessToken) {',
          "  pm.collectionVariables.set('accessToken', res.data.accessToken);",
          "  pm.collectionVariables.set('refreshToken', res.data.refreshToken);",
          '}',
        ] } }];
      }
      // collection auth applies; public requests keep noauth when the spec says security: []
    }
  };
  walk(col.item);
  return `${JSON.stringify(col, null, 2)}\n`;
}

const outputs: Record<string, string> = {
  'docs/FRONTEND_API_GUIDE.md': guide,
  'docs/API_ENDPOINT_INDEX.csv': csv,
  'docs/API_RENAME_MAP.md': renameMap,
  'docs/postman/Zellavora-Nexus.postman_collection.json': await postman(),
};

mkdirSync('docs/postman', { recursive: true });
if (check) {
  const stale = Object.entries(outputs).filter(([f, c]) => !existsSync(f) || readFileSync(f, 'utf8').replace(/\r\n/g, '\n') !== c.replace(/\r\n/g, '\n'));
  if (stale.length) {
    console.error(`Stale documentation artifacts (run \`npm run docs:artifacts\`): ${stale.map(([f]) => f).join(', ')}`);
    process.exit(1);
  }
  console.log('documentation artifacts up to date');
} else {
  for (const [f, c] of Object.entries(outputs)) writeFileSync(f, c);
  console.log(`wrote ${Object.keys(outputs).join(', ')}`);
}
