/** Generates docs/ERD.md (Mermaid) from the live schema: tables, key columns and foreign keys. */
import 'dotenv/config';
import { writeFileSync } from 'node:fs';
import knexLib from 'knex';

const url = process.env.MIGRATOR_DATABASE_URL ?? process.env.DATABASE_URL;
if (!url) { console.error('MIGRATOR_DATABASE_URL or DATABASE_URL is required'); process.exit(2); }
const db = knexLib({ client: 'pg', connection: url });

const cols = (await db.raw(
  `SELECT table_name, column_name, data_type, is_nullable FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name NOT LIKE 'knex_%' ORDER BY table_name, ordinal_position`,
)).rows as { table_name: string; column_name: string; data_type: string; is_nullable: string }[];
const fks = (await db.raw(
  `SELECT tc.table_name AS child, ccu.table_name AS parent, kcu.column_name AS col
     FROM information_schema.table_constraints tc
     JOIN information_schema.key_column_usage kcu ON kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema
     JOIN information_schema.constraint_column_usage ccu ON ccu.constraint_name = tc.constraint_name AND ccu.table_schema = tc.table_schema
    WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = 'public' ORDER BY 1, 2`,
)).rows as { child: string; parent: string; col: string }[];
const rls = new Set(((await db.raw(`SELECT relname FROM pg_class WHERE relrowsecurity AND relkind = 'r'`)).rows as { relname: string }[]).map((r) => r.relname));

const byTable = new Map<string, typeof cols>();
for (const c of cols) byTable.set(c.table_name, [...(byTable.get(c.table_name) ?? []), c]);
const typeOf = (t: string) => t.replace(/ /g, '_').replace('character_varying', 'varchar').replace('timestamp_with_time_zone', 'timestamptz');

let md = '# Entity-relationship diagram\n\n_Generated by `npm run docs:erd` from the live schema._ Tables marked **RLS** are tenant-owned and protected by row-level security.\n\n';
md += `Tables: ${byTable.size} · Foreign keys: ${fks.length}\n\n\`\`\`mermaid\nerDiagram\n`;
for (const [t, cs] of byTable) {
  md += `  ${t} {\n`;
  for (const c of cs.slice(0, 12)) md += `    ${typeOf(c.data_type)} ${c.column_name}${c.is_nullable === 'NO' && c.column_name === 'id' ? ' PK' : ''}\n`;
  if (cs.length > 12) md += `    string _more_${cs.length - 12}_columns\n`;
  md += '  }\n';
}
const seen = new Set<string>();
for (const f of fks) {
  const k = `${f.parent}->${f.child}:${f.col}`;
  if (seen.has(k)) continue;
  seen.add(k);
  md += `  ${f.parent} ||--o{ ${f.child} : "${f.col}"\n`;
}
md += '```\n\n## Tenant-owned tables (RLS enforced)\n\n' + [...rls].sort().map((t) => `- ${t}`).join('\n') + '\n';
writeFileSync('docs/ERD.md', md);
console.log(`ERD written: ${byTable.size} tables, ${fks.length} relationships`);
await db.destroy();
