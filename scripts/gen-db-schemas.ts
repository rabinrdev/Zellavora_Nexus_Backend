/**
 * Generates src/platform/openapi/db-rows.generated.ts: column name/type/nullability for every public table, so that
 * response schemas for row pass-through endpoints are derived from the database rather than guessed.
 * Requires a migrated database (DATABASE_URL/MIGRATOR_DATABASE_URL, default: the local embedded Postgres).
 */
import { writeFileSync } from 'node:fs';
import knexLib from 'knex';

const url = process.env.MIGRATOR_DATABASE_URL ?? 'postgres://postgres:postgres@localhost:54329/nexus';
const db = knexLib({ client: 'pg', connection: url });
const rows = (await db.raw(
  `select table_name, column_name, data_type, udt_name, is_nullable
     from information_schema.columns where table_schema = 'public' and table_name not like 'knex_%' and table_name not like 'pgboss%'
     order by table_name, ordinal_position`,
)).rows as { table_name: string; column_name: string; data_type: string; udt_name: string; is_nullable: string }[];
await db.destroy();

const kind = (r: (typeof rows)[number]): string => {
  const t = r.data_type;
  if (r.udt_name === 'uuid') return 'uuid';
  if (t === 'timestamp with time zone' || t === 'timestamp without time zone') return 'timestamp';
  if (t === 'date') return 'date';
  if (t === 'boolean') return 'boolean';
  if (['integer', 'smallint'].includes(t)) return 'integer';
  if (['bigint', 'numeric'].includes(t)) return 'decimal';
  if (['real', 'double precision'].includes(t)) return 'number';
  if (t === 'jsonb' || t === 'json') return 'json';
  if (t === 'ARRAY') return 'stringArray';
  return 'string';
};

const tables: Record<string, Record<string, string>> = {};
for (const r of rows) (tables[r.table_name] ??= {})[r.column_name] = `${kind(r)}${r.is_nullable === 'YES' ? '?' : ''}`;
const body = Object.entries(tables)
  .map(([t, cols]) => `  ${t}: { ${Object.entries(cols).map(([c, k]) => `${c}: '${k}'`).join(', ')} },`)
  .join('\n');
writeFileSync(
  'src/platform/openapi/db-rows.generated.ts',
  `// GENERATED by scripts/gen-db-schemas.ts — do not edit. Column kinds: '?' suffix = nullable.\nexport const DB_ROWS: Record<string, Record<string, string>> = {\n${body}\n};\n`,
);
console.log(`wrote ${Object.keys(tables).length} tables`);
